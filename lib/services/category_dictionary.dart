    return jsonEncode(
      entries
          .map(
            (e) => {'keyword': e.keyword, 'key': e.categoryKey, 'label': e.categoryLabel},
          )
          .toList(),
    );
  }

  /// 自定义词库 JSON 解码；格式异常时返回空列表（不抛错）。
  static List<CategoryDictEntry> decodeCustom(String? raw) {
    if (raw == null || raw.isEmpty) return const [];
    try {
      final list = jsonDecode(raw);
      if (list is! List) return const [];
      final result = <CategoryDictEntry>[];
      for (final e in list) {
        if (e is Map) {
          final keyword = e['keyword']?.toString() ?? '';
          final key = e['key']?.toString() ?? '';
          final label = e['label']?.toString() ?? '';
          if (keyword.isNotEmpty && key.isNotEmpty) {
            result.add(
              CategoryDictEntry(
                keyword: keyword,
                categoryKey: key,
                categoryLabel: label,
              ),
            );
          }
        }
      }
      return result;
    } catch (_) {
      return const [];
    }
  }
